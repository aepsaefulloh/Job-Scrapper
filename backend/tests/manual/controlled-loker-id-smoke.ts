import 'dotenv/config';
import { loadEnv } from '../../src/config/env.js';
import { createUserSupabaseClient } from '../../src/infrastructure/supabase/supabase-user-client.js';
import { SupabaseProfileRepository } from '../../src/infrastructure/supabase/profile-repository.js';
import { SupabaseSearchProfileRepository } from '../../src/search/search-profile.repository.js';
import { SearchProfileService } from '../../src/search/search-profile.service.js';
import { SearchPlanner } from '../../src/search/search-planner.js';
import { LokerIdScraper } from '../../src/scraping/providers/loker-id/loker-id.scraper.js';
import { CamoufoxBrowserService } from '../../src/browser/camoufox.browser.js';
import { ScraperOrchestrator } from '../../src/scraping/scraper.orchestrator.js';
import { JobIngestionService } from '../../src/services/job-ingestion-service.js';
import { SupabaseJobRepository } from '../../src/infrastructure/supabase/job-repository.js';
import { SupabaseScrapeRunRepository } from '../../src/infrastructure/supabase/scrape-run-repository.js';
import { SumoPodProvider } from '../../src/ai/providers/sumopod.provider.js';
import { EmbeddingService } from '../../src/ai/embedding/embedding.service.js';
import { SupabaseMatchingRepository } from '../../src/matching/matching.repository.js';
import { VectorSearchService } from '../../src/matching/vector-search.service.js';
import { DefaultMatchingService } from '../../src/services/matching-service.js';
import { LlmService } from '../../src/ai/completion/llm.service.js';
import { StructuredLogger } from '../../src/logging/logger.js';

async function main() {
  const env = loadEnv(process.env);
  const logger = new StructuredLogger();

  const email = process.env.TEST_USER_A_EMAIL;
  const password = process.env.TEST_USER_A_PASSWORD;
  if (!email || !password) {
    throw new Error('TEST_USER_A_EMAIL and TEST_USER_A_PASSWORD must be set in .env');
  }

  console.log(`Authenticating test user: ${email}...`);
  const anonClient = createUserSupabaseClient(env.supabaseAnonKey, env);
  const { data: authData, error: authError } = await anonClient.auth.signInWithPassword({
    email,
    password,
  });

  if (authError || !authData.session) {
    throw new Error(`Auth failed: ${authError?.message}`);
  }

  const accessToken = authData.session.access_token;
  const candidateId = authData.user.id;
  console.log(`Authenticated candidate ID: ${candidateId}`);

  const userClient = createUserSupabaseClient(accessToken, env);
  const profileRepo = new SupabaseProfileRepository(userClient);
  const searchProfileRepo = new SupabaseSearchProfileRepository(userClient);
  const searchProfileService = new SearchProfileService(searchProfileRepo);
  const searchPlanner = new SearchPlanner();

  // 1. Get candidate profile
  const candidateProfile = await profileRepo.getActiveProfile(candidateId);
  if (!candidateProfile) {
    throw new Error('Candidate has no active profile. Upload a profile first.');
  }

  // 2. Derive or get Search Profile
  const searchProfile = await searchProfileService.getOrDerive(candidateId, candidateProfile);
  console.log(`Target roles: ${JSON.stringify(searchProfile.targetRoles)}`);
  console.log(`Sources: ${JSON.stringify(searchProfile.sources)}`);

  // 3. Search Planner generates candidate intents
  const intents = searchPlanner.createIntents(searchProfile, { defaultMaxPages: 1 });
  const lokerIntent = intents.find((i) => i.source === 'loker-id');
  if (!lokerIntent) {
    throw new Error('No loker-id intent generated by search planner.');
  }
  console.log(`Selected candidate intent:`, lokerIntent);

  // 4. Setup Scraper and Pipeline
  if (!env.camoufoxExecutablePath) {
    throw new Error('CAMOUFOX_EXECUTABLE_PATH is required.');
  }

  const provider = new SumoPodProvider({ baseUrl: env.aiBaseUrl, apiKey: env.aiApiKey });
  const matchingRepo = new SupabaseMatchingRepository(userClient);
  const embeddings = new EmbeddingService(provider, {
    model: env.aiEmbeddingModel,
    dimensions: env.aiEmbeddingDimensions,
  });

  const embeddingRunner = {
    embed: async (jobId: string) => {
      console.log(`Embedding job: ${jobId}...`);
      const jobContext = await matchingRepo.getJobContext(candidateId, jobId);
      const result = await embeddings.embedText(jobContext.text);
      const { error } = await userClient
        .from('jobs')
        .update({
          embedding_status: 'ready',
          embedding: result.vector as never,
          embedding_model: result.model,
          embedding_dimensions: result.dimensions,
          embedding_error: null,
          embedding_updated_at: new Date().toISOString(),
        })
        .eq('candidate_id', candidateId)
        .eq('id', jobId);
      if (error) throw new Error(`Embedding update failed: ${error.message}`);
    },
  };

  const scrapeRunRepo = new SupabaseScrapeRunRepository(userClient);
  const jobRepo = new SupabaseJobRepository(userClient);
  const ingestion = new JobIngestionService(jobRepo);

  const lokerIdScraper = new LokerIdScraper(
    new CamoufoxBrowserService(env.camoufoxExecutablePath),
    'https://www.loker.id',
    logger
  );

  const orchestrator = new ScraperOrchestrator(
    [lokerIdScraper],
    ingestion,
    embeddingRunner,
    logger
  );

  // 5. Start Scrape Run
  console.log(`Starting scrape_run for Loker.id...`);
  const run = await scrapeRunRepo.start({
    candidateId,
    source: lokerIntent.source,
    keyword: lokerIntent.keyword,
    location: lokerIntent.location,
    metadata: { trigger: 'manual', smokeTest: true },
  });
  console.log(`Scrape run registered with ID: ${run.id}`);

  // 6. Execute 1 controlled page
  const summary = await orchestrator.run({
    candidateId,
    source: lokerIntent.source,
    query: {
      keyword: lokerIntent.keyword,
      location: lokerIntent.location,
      maxPages: 1,
    },
  });

  // 7. Finish Scrape Run
  const status = summary.failed > 0 && summary.inserted === 0 ? 'failed' : summary.failed > 0 ? 'partial' : 'completed';
  await scrapeRunRepo.finish(run.id, {
    status,
    discovered: summary.discovered,
    inserted: summary.inserted,
    updated: summary.updated,
    duplicates: summary.duplicates,
    failed: summary.failed,
  });

  // 8. Run matching check
  console.log('Evaluating matching recommendations...');
  const existingProfileEmbedding = await matchingRepo.getProfileEmbedding(candidateId);
  if (!existingProfileEmbedding) {
    console.log('Candidate profile embedding missing, generating now...');
    const candidateContext = await matchingRepo.getCandidateContext(candidateId);
    const profileEmb = await embeddings.embedText(candidateContext.text);
    await userClient
      .from('profiles')
      .update({
        embedding_status: 'ready',
        embedding: profileEmb.vector as never,
        embedding_model: profileEmb.model,
        embedding_dimensions: profileEmb.dimensions,
        embedding_updated_at: new Date().toISOString(),
      })
      .eq('candidate_id', candidateId)
      .eq('is_active', true);
    console.log('Candidate profile embedding saved.');
  }

  const vectorSearch = new VectorSearchService(matchingRepo, { maxLimit: 200 });
  const llmService = new LlmService(provider);
  const matchingService = new DefaultMatchingService(vectorSearch, matchingRepo, llmService, env.aiChatModel);
  const recommendations = await matchingService.recommend(candidateId, 5, 0.3);

  console.log('\n================ SMOKE TEST RESULTS ================');
  console.log(`Keyword: "${lokerIntent.keyword}"`);
  console.log(`Location: "${lokerIntent.location ?? 'all'}"`);
  console.log(`Scrape Run ID: ${run.id}`);
  console.log(`Run Status: ${status}`);
  console.log(`Jobs Discovered: ${summary.discovered}`);
  console.log(`Jobs Inserted: ${summary.inserted}`);
  console.log(`Jobs Updated: ${summary.updated}`);
  console.log(`Duplicates: ${summary.duplicates}`);
  console.log(`Failed: ${summary.failed}`);
  console.log(`Total Recommendations Available: ${recommendations.length}`);
  console.log('====================================================\n');

  if (summary.discovered === 0) {
    throw new Error('Loker.id scrape returned 0 jobs.');
  }

  console.log('Controlled Loker.id live smoke test succeeded!');
}

main().catch((err) => {
  console.error('Smoke test failed:', err);
  process.exit(1);
});
